//! smpl-common — shared initialisation code for all smplOS Slint/Winit apps.
//!
//! Every smplOS GUI app needs:
//!   1. Skia CPU rasterization with premultiplied ARGB presentation (no GPU context)
//!   2. `with_decorations(false)` — no CSD frame
//!   3. `with_name(app_id, app_id)` — sets Wayland app_id for windowrulev2
//!   4. A fixed logical size so Hyprland can float + size it via windowrule
//!   5. A Tokio runtime context on the UI thread — Slint reads the colour scheme over D-Bus
//!      through zbus, which is built for Tokio and panics (and aborts) without one
//!   6. A crash log, because these apps are launched with stderr discarded
//!
//! The pinned Skia/softbuffer patches preserve alpha on the CPU path. Do not
//! replace them with upstream opaque software surfaces or select a GPU renderer.
//!
//! Without ALL of these, either the blur breaks, the window gets decorated,
//! or Hyprland can't target it with windowrulev2.

pub mod crash_log;
pub mod keybindings;
mod runtime;
pub mod theme;

use i_slint_backend_winit::winit::dpi::LogicalSize;
use i_slint_backend_winit::winit::platform::wayland::WindowAttributesExtWayland;
use slint::PlatformError;

/// Initialise the Slint backend for a smplOS popup window.
///
/// Must be called **before** creating any Slint component, on the thread that will run the
/// event loop.
///
/// # Arguments
/// * `app_id` – Wayland `app_id` / instance name (matches binary name).
///   Must match the `initialClass` in Hyprland `windowrulev2`. Also names the crash log,
///   `$XDG_STATE_HOME/smplos/<app_id>/crash.log`.
/// * `width` – Logical width in DIPs.
/// * `height` – Logical height in DIPs.
///
/// # Example
/// ```ignore
/// // MainWindow is generated by slint::include_modules!() in each consuming crate.
/// smpl_common::init("start-menu", 420.0, 680.0).expect("backend init failed");
/// let ui = MainWindow::new().unwrap();
/// ui.run().unwrap();
/// ```
pub fn init(app_id: &'static str, width: f64, height: f64) -> Result<(), PlatformError> {
    crash_log::install(app_id);
    runtime::enter_ui_thread()?;

    let backend = i_slint_backend_winit::Backend::builder()
        // CPU from the first frame: no GPU probe, VRAM allocations, or lost state
        // on renderer restart. Patched Skia/softbuffer retain per-pixel alpha.
        .with_renderer_name("skia-software")
        .with_window_attributes_hook(move |attrs| {
            attrs
                // Sets Wayland app_id so `windowrulev2 = float, initialClass:start-menu`
                // (and blur/opacity rules) can target this window specifically.
                .with_name(app_id, app_id)
                // No client-side decorations — adds an opaque frame otherwise.
                .with_decorations(false)
                // Fixed logical size. Hyprland's `windowrule = size W H` overrides
                // this at the compositor level, but we set it here too so the window
                // opens at the right size before Hyprland applies its rules.
                .with_inner_size(LogicalSize::new(width, height))
        })
        .build()?;

    slint::platform::set_platform(Box::new(backend))
        .map_err(|e| PlatformError::Other(e.to_string()))?;

    Ok(())
}
