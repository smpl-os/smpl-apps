//! `$HOME/.config/hypr/monitors.conf`: the grammar and rule semantics shared
//! with the smplOS Lua loader, and the Settings writer.
//!
//! Grammar (hyprlang): `#` starts a comment anywhere and `##` is a literal
//! `#`. `monitor = <fields>` splits on commas; fields are trimmed. Forms:
//! * full `<sel>, <mode>, <position>, <scale>[, <key>, <value>]…` creates a
//!   fresh rule (transform 0, enabled), replacing any rule with the identical
//!   selector and moving it to the end. Options stop at the first empty key;
//!   integers are plain decimals and an invalid transform leaves 0;
//! * `<sel>, disable|disabled`: a fresh disabled rule, replaced the same way;
//! * `<sel>, transform, <n>`: copies the identical-selector rule with that
//!   transform to the end; a no-op without one;
//! * `<sel>, addreserved, <top>, <bottom>, <left>, <right>`: modifies the
//!   identical-selector rule in place, else appends a default rule.
//!
//! An output's effective rule is the last rule whose selector matches it
//! (`desc:` prefix or exact connector); the catch-all is ignored here.

use std::fs::{self, OpenOptions};
use std::io::{ErrorKind, Write};
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use super::monitor::{Mode, Output};
use super::scale;

pub const HEADER: &str =
    "# Managed by smplOS Settings > Display. Lines for displays that are not connected are kept.";
const LEGACY_HEADERS: [&str; 1] =
    ["# Generated by settings -- edit freely, re-running settings will overwrite."];
/// Options carried from an output's previous rule onto the rewritten line.
const CARRIED_KEYS: [&str; 6] = [
    "vrr",
    "bitdepth",
    "cm",
    "sdrbrightness",
    "sdrsaturation",
    "icc",
];
const BACKUP_PREFIX: &str = "monitors.conf.bak-";
const BACKUPS_KEPT: usize = 5;

/// Removes a hyprlang comment; `##` is unescaped to a literal `#`.
pub fn strip_comment(line: &str) -> String {
    let mut content = String::with_capacity(line.len());
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '#' {
            content.push(c);
        } else if chars.peek() == Some(&'#') {
            chars.next();
            content.push('#');
        } else {
            break;
        }
    }
    content
}

fn escape(value: &str) -> String {
    value.replace('#', "##")
}

fn is_integer(text: &str) -> bool {
    let digits = text.strip_prefix('-').unwrap_or(text);
    !digits.is_empty() && digits.bytes().all(|b| b.is_ascii_digit())
}

fn parse_transform(text: &str) -> Option<i32> {
    if !is_integer(text) {
        return None;
    }
    text.parse().ok().filter(|t| (0..=7).contains(t))
}

#[derive(Debug, Clone, PartialEq)]
pub enum Form {
    Full {
        mode: String,
        position: String,
        scale: String,
        transform: i32,
        options: Vec<(String, String)>,
    },
    Disable,
    /// `None` when the value is not a valid transform (the line is ignored).
    Transform(Option<i32>),
    AddReserved(Vec<String>),
}

#[derive(Debug, Clone, PartialEq)]
pub struct MonitorLine {
    pub selector: String,
    pub form: Form,
}

/// Parses one line; `None` for anything that is not a `monitor` keyword.
pub fn parse_line(line: &str) -> Option<MonitorLine> {
    let content = strip_comment(line);
    let value = content
        .trim()
        .strip_prefix("monitor")?
        .trim_start()
        .strip_prefix('=')?;
    let fields: Vec<&str> = value.split(',').map(str::trim).collect();
    let field = |index: usize| fields.get(index).copied().unwrap_or("");
    let form = match field(1) {
        "disable" | "disabled" => Form::Disable,
        "transform" => Form::Transform(parse_transform(field(2))),
        "addreserved" => Form::AddReserved(fields.iter().skip(2).map(|f| f.to_string()).collect()),
        mode => {
            let mut transform = 0;
            let mut options = Vec::new();
            let mut index = 4;
            while index < fields.len() && !fields[index].is_empty() {
                let (key, value) = (fields[index], field(index + 1));
                if key == "transform" {
                    if let Some(valid) = parse_transform(value) {
                        transform = valid;
                    }
                } else {
                    options.push((key.to_string(), value.to_string()));
                }
                index += 2;
            }
            Form::Full {
                mode: mode.to_string(),
                position: field(2).to_string(),
                scale: field(3).to_string(),
                transform,
                options,
            }
        }
    };
    Some(MonitorLine {
        selector: field(0).to_string(),
        form,
    })
}

/// An explicit resolution, with a refresh rate when one was given.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct RuleMode {
    pub width: i32,
    pub height: i32,
    pub refresh: Option<f64>,
}

impl RuleMode {
    pub fn label(&self) -> String {
        match self.refresh {
            Some(refresh) => Mode {
                width: self.width,
                height: self.height,
                refresh,
            }
            .label(),
            None => format!("{}×{}", self.width, self.height),
        }
    }
}

fn leading_number(text: &str) -> Option<f64> {
    let end = text
        .char_indices()
        .find(|(_, c)| !(c.is_ascii_digit() || *c == '.'))
        .map_or(text.len(), |(i, _)| i);
    text[..end].parse().ok()
}

fn parse_rule_mode(text: &str) -> Option<RuleMode> {
    if ["pref", "highrr", "highres", "maxwidth", "modeline"]
        .iter()
        .any(|keyword| text.starts_with(keyword))
    {
        return None;
    }
    let (resolution, refresh) = match text.split_once('@') {
        Some((resolution, refresh)) => (resolution, Some(leading_number(refresh.trim())?)),
        None => (text, None),
    };
    let (width, height) = resolution.split_once('x')?;
    Some(RuleMode {
        width: width.trim().parse().ok()?,
        height: height.trim().parse().ok()?,
        refresh,
    })
}

fn parse_position(text: &str) -> Option<(i32, i32)> {
    if text.is_empty() || text.starts_with("auto") {
        return None;
    }
    let (x, y) = text.split_once('x')?;
    Some((x.trim().parse().ok()?, y.trim().parse().ok()?))
}

fn parse_scale(text: &str) -> Option<f64> {
    if text.is_empty() || text.starts_with("auto") {
        return None;
    }
    let value: f64 = text.parse().ok().filter(|v: &f64| v.is_finite())?;
    // Hyprland rejects scales below 0.25 and uses 1 instead.
    Some(if value < 0.25 { 1.0 } else { value })
}

/// One monitor rule after applying the file's lines in order.
#[derive(Debug, Clone, PartialEq)]
pub struct Rule {
    pub selector: String,
    pub disabled: bool,
    pub mode: Option<RuleMode>,
    pub position: Option<(i32, i32)>,
    pub scale: Option<f64>,
    pub transform: i32,
    pub options: Vec<(String, String)>,
}

impl Rule {
    fn fresh(selector: &str) -> Self {
        Self {
            selector: selector.to_string(),
            disabled: false,
            mode: None,
            position: None,
            scale: None,
            transform: 0,
            options: Vec::new(),
        }
    }
}

/// The rule list Hyprland builds from this file, in rule order.
pub fn rules(text: &str) -> Vec<Rule> {
    let mut rules: Vec<Rule> = Vec::new();
    for line in text.lines() {
        let Some(MonitorLine { selector, form }) = parse_line(line) else {
            continue;
        };
        match form {
            Form::Full {
                mode,
                position,
                scale,
                transform,
                options,
            } => {
                rules.retain(|rule| rule.selector != selector);
                rules.push(Rule {
                    mode: parse_rule_mode(&mode),
                    position: parse_position(&position),
                    scale: parse_scale(&scale),
                    transform,
                    options,
                    ..Rule::fresh(&selector)
                });
            }
            Form::Disable => {
                rules.retain(|rule| rule.selector != selector);
                rules.push(Rule {
                    disabled: true,
                    ..Rule::fresh(&selector)
                });
            }
            Form::Transform(Some(transform)) => {
                if let Some(index) = rules.iter().position(|rule| rule.selector == selector) {
                    let mut rule = rules.remove(index);
                    rule.transform = transform;
                    rules.push(rule);
                }
            }
            Form::Transform(None) => {}
            Form::AddReserved(_) => {
                if !rules.iter().any(|rule| rule.selector == selector) {
                    rules.push(Rule::fresh(&selector));
                }
            }
        }
    }
    rules
}

/// The last rule whose selector matches `output` (never the catch-all).
pub fn effective<'a>(rules: &'a [Rule], output: &Output) -> Option<&'a Rule> {
    rules
        .iter()
        .rev()
        .find(|rule| output.matches_selector(&rule.selector))
}

/// `desc:<description>` when it can only ever match this output, otherwise
/// the connector name. Descriptions survive connector renumbering (DP-3
/// becoming DP-4 after a re-plug), connector names do not.
pub fn choose_selector(output: &Output, outputs: &[Output]) -> String {
    let description = output.description.as_str();
    let usable = !description.is_empty()
        && description.trim() == description
        && !description
            .chars()
            .any(|c| c == '#' || c == ',' || c.is_control());
    if usable {
        let selector = format!("desc:{description}");
        if outputs
            .iter()
            .filter(|other| other.name != output.name)
            .all(|other| !other.matches_selector(&selector))
        {
            return selector;
        }
    }
    output.name.clone()
}

/// What Apply writes for one output.
#[derive(Debug, Clone, PartialEq)]
pub struct Target {
    pub name: String,
    pub mode: Mode,
    pub x: i32,
    pub y: i32,
    pub scale: f64,
    pub transform: i32,
}

/// A target with its chosen selector.
#[derive(Debug, Clone, PartialEq)]
pub struct Planned {
    pub selector: String,
    pub target: Target,
}

pub fn format_line(selector: &str, target: &Target, options: &[(String, String)]) -> String {
    let mut line = format!(
        "monitor = {selector}, {}, {}x{}, {}, transform, {}",
        target.mode.conf_text(),
        target.x,
        target.y,
        scale::format(target.scale),
        target.transform
    );
    for (key, value) in options {
        line.push_str(&format!(", {}, {}", escape(key), escape(value)));
    }
    line
}

fn valid_option(key: &str, value: &str) -> bool {
    match key {
        "vrr" => is_integer(value),
        "sdrbrightness" | "sdrsaturation" => value.parse::<f64>().is_ok_and(f64::is_finite),
        _ => !value.is_empty(),
    }
}

fn carried_options(rule: &Rule) -> Vec<(String, String)> {
    if rule.disabled {
        return Vec::new();
    }
    rule.options
        .iter()
        .filter(|(key, value)| CARRIED_KEYS.contains(&key.as_str()) && valid_option(key, value))
        .cloned()
        .collect()
}

fn is_header(line: &str) -> bool {
    let line = line.trim();
    line == HEADER || LEGACY_HEADERS.contains(&line)
}

fn split_lines(text: &str) -> Vec<&str> {
    let mut lines: Vec<&str> = text.split('\n').collect();
    if text.ends_with('\n') {
        lines.pop();
    }
    lines
}

/// Rewrites `existing` for the planned outputs.
///
/// Every line whose selector matches a written output is replaced; options
/// other than transform (vrr, bitdepth, cm, sdr*, icc) from that output's
/// effective rule move onto the new line, and its `addreserved` lines are
/// re-emitted after it. Everything else (comments, the catch-all, rules for
/// disconnected, disabled, virtual or mirroring outputs, unknown content) is
/// kept verbatim in order. A line that also matches a present output that is
/// not being written is kept too, so that output is never changed.
pub fn merge(existing: &str, planned: &[Planned], outputs: &[Output]) -> String {
    let rules = rules(existing);
    let is_planned = |output: &&Output| planned.iter().any(|p| p.target.name == output.name);
    let written: Vec<&Output> = outputs.iter().filter(is_planned).collect();
    let others: Vec<&Output> = outputs.iter().filter(|o| !is_planned(o)).collect();
    let mut kept: Vec<&str> = Vec::new();
    let mut reserved: Vec<(String, String)> = Vec::new();
    for line in split_lines(existing) {
        if is_header(line) {
            continue;
        }
        if let Some(parsed) = parse_line(line) {
            let hits: Vec<&&Output> = written
                .iter()
                .filter(|output| output.matches_selector(&parsed.selector))
                .collect();
            let shared = others
                .iter()
                .any(|output| output.matches_selector(&parsed.selector));
            if !hits.is_empty() && !shared {
                if let Form::AddReserved(values) = &parsed.form {
                    let values = values
                        .iter()
                        .map(|v| escape(v))
                        .collect::<Vec<_>>()
                        .join(", ");
                    for output in hits {
                        reserved.push((output.name.clone(), values.clone()));
                    }
                }
                continue;
            }
        }
        kept.push(line);
    }
    while kept.first().is_some_and(|line| line.trim().is_empty()) {
        kept.remove(0);
    }
    while kept.last().is_some_and(|line| line.trim().is_empty()) {
        kept.pop();
    }

    let mut ordered: Vec<&Planned> = planned.iter().collect();
    ordered.sort_by(|a, b| {
        (a.target.y, a.target.x, &a.target.name).cmp(&(b.target.y, b.target.x, &b.target.name))
    });
    let mut text = format!("{HEADER}\n");
    if !kept.is_empty() {
        text.push('\n');
        for line in kept {
            text.push_str(line);
            text.push('\n');
        }
    }
    if !ordered.is_empty() {
        text.push('\n');
    }
    for planned in ordered {
        let options = outputs
            .iter()
            .find(|output| output.name == planned.target.name)
            .and_then(|output| effective(&rules, output))
            .map(carried_options)
            .unwrap_or_default();
        text.push_str(&format_line(&planned.selector, &planned.target, &options));
        text.push('\n');
        // In-place modifications: the last of identical lines decides, so
        // keep the last occurrence of duplicates.
        let mut lines: Vec<&str> = Vec::new();
        for (name, values) in reserved.iter().rev() {
            if *name == planned.target.name && !lines.contains(&values.as_str()) {
                lines.push(values);
            }
        }
        for values in lines.into_iter().rev() {
            text.push_str(&format!(
                "monitor = {}, addreserved, {values}\n",
                planned.selector
            ));
        }
    }
    text
}

/// `monitors.conf` as Hyprland reads it (HOME-based, never XDG_CONFIG_HOME)
/// and, for a symlink, the file that is actually read and replaced.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConfPath {
    pub link: PathBuf,
    pub target: PathBuf,
}

impl ConfPath {
    pub fn for_home(home: &Path) -> Result<Self, String> {
        let link = home.join(".config/hypr/monitors.conf");
        let target = match fs::symlink_metadata(&link) {
            Ok(meta) if meta.file_type().is_symlink() => {
                let target = fs::canonicalize(&link).map_err(|error| {
                    format!(
                        "{} is a symlink that can't be resolved: {error}",
                        link.display()
                    )
                })?;
                if !fs::metadata(&target).is_ok_and(|meta| meta.is_file()) {
                    return Err(format!(
                        "{} does not point to a regular file",
                        link.display()
                    ));
                }
                target
            }
            Ok(meta) if meta.is_file() => link.clone(),
            Ok(_) => return Err(format!("{} is not a regular file", link.display())),
            Err(error) if error.kind() == ErrorKind::NotFound => link.clone(),
            Err(error) => return Err(format!("can't inspect {}: {error}", link.display())),
        };
        Ok(Self { link, target })
    }

    /// The current content; `None` when the file does not exist.
    pub fn read(&self) -> Result<Option<String>, String> {
        match fs::read_to_string(&self.target) {
            Ok(text) => Ok(Some(text)),
            Err(error) if error.kind() == ErrorKind::NotFound => Ok(None),
            Err(error) => Err(format!("can't read {}: {error}", self.target.display())),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Written {
    /// The new content was byte-identical; nothing was touched.
    Unchanged,
    Replaced,
}

struct Temporary(PathBuf);

impl Drop for Temporary {
    fn drop(&mut self) {
        if let Err(error) = fs::remove_file(&self.0) {
            if error.kind() != ErrorKind::NotFound {
                eprintln!("[settings] cannot remove display temporary file: {error}");
            }
        }
    }
}

fn io_error(action: &str, path: &Path, error: std::io::Error) -> String {
    format!("can't {action} {}: {error}", path.display())
}

/// Copies the previous content to `monitors.conf.bak-YYYYmmdd-HHMMSS` next
/// to the path Hyprland reads (where the OS monitors-guard restores from).
fn backup(path: &ConfPath, previous: &str, stamp: &str) -> Result<PathBuf, String> {
    let directory = path.link.parent().ok_or("monitors.conf has no directory")?;
    let mut candidate = directory.join(format!("{BACKUP_PREFIX}{stamp}"));
    for attempt in 2..100 {
        match OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o600)
            .open(&candidate)
        {
            Ok(mut file) => {
                if let Ok(meta) = fs::metadata(&path.target) {
                    file.set_permissions(meta.permissions())
                        .map_err(|e| io_error("set permissions on", &candidate, e))?;
                }
                file.write_all(previous.as_bytes())
                    .and_then(|()| file.sync_all())
                    .map_err(|e| io_error("write", &candidate, e))?;
                return Ok(candidate);
            }
            Err(error) if error.kind() == ErrorKind::AlreadyExists => {
                candidate = directory.join(format!("{BACKUP_PREFIX}{stamp}-{attempt}"));
            }
            Err(error) => return Err(io_error("create", &candidate, error)),
        }
    }
    Err(format!("too many backups named {BACKUP_PREFIX}{stamp}"))
}

/// Sort key of a Settings backup name: (YYYYmmdd-HHMMSS, collision number).
fn backup_key(name: &str) -> Option<(String, u32)> {
    let rest = name.strip_prefix(BACKUP_PREFIX)?;
    let stamp = rest.get(..15)?;
    let bytes = stamp.as_bytes();
    let digits = |range: std::ops::Range<usize>| bytes[range].iter().all(u8::is_ascii_digit);
    if bytes[8] != b'-' || !digits(0..8) || !digits(9..15) {
        return None;
    }
    let number = match &rest[15..] {
        "" => 1,
        suffix => {
            let digits = suffix.strip_prefix('-')?;
            if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_digit()) {
                return None;
            }
            digits.parse().ok()?
        }
    };
    Some((stamp.to_string(), number))
}

/// Keeps only the newest Settings backups (other files are never touched).
/// The backup just written always survives, even if the clock went back.
fn prune_backups(directory: &Path, created: Option<&Path>) {
    let Ok(entries) = fs::read_dir(directory) else {
        return;
    };
    let mut backups: Vec<((String, u32), PathBuf)> = entries
        .flatten()
        .filter(|entry| Some(entry.path().as_path()) != created)
        .filter_map(|entry| {
            let key = backup_key(entry.file_name().to_str()?)?;
            entry
                .file_type()
                .ok()?
                .is_file()
                .then(|| (key, entry.path()))
        })
        .collect();
    backups.sort();
    let kept = BACKUPS_KEPT - usize::from(created.is_some());
    let excess = backups.len().saturating_sub(kept);
    for (_, path) in backups.into_iter().take(excess) {
        if let Err(error) = fs::remove_file(&path) {
            eprintln!("[settings] cannot prune {}: {error}", path.display());
        }
    }
}

/// Atomically replaces the file with `text` unless it is byte-identical:
/// back up the previous content, write a temporary file in the target's
/// directory with the same mode, fsync, check nobody changed the file in the
/// meantime, then rename over the target (a symlink stays a symlink).
pub fn replace(
    path: &ConfPath,
    previous: Option<&str>,
    text: &str,
    stamp: &str,
) -> Result<Written, String> {
    static NEXT: AtomicU64 = AtomicU64::new(0);
    if previous == Some(text) {
        return Ok(Written::Unchanged);
    }
    const CHANGED: &str = "monitors.conf changed while saving, so nothing was replaced";
    if path.read()?.as_deref() != previous {
        return Err(CHANGED.into());
    }
    let directory = path
        .target
        .parent()
        .ok_or("monitors.conf has no directory")?;
    fs::create_dir_all(directory).map_err(|e| io_error("create", directory, e))?;
    let created = match previous {
        Some(previous) => Some(backup(path, previous, stamp)?),
        None => None,
    };
    let temporary = Temporary(directory.join(format!(
        ".monitors.conf.{}.{}.tmp",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    )));
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o644)
        .open(&temporary.0)
        .map_err(|e| io_error("create", &temporary.0, e))?;
    if previous.is_some() {
        let permissions = fs::metadata(&path.target)
            .map_err(|e| io_error("inspect", &path.target, e))?
            .permissions();
        file.set_permissions(permissions)
            .map_err(|e| io_error("set permissions on", &temporary.0, e))?;
    }
    file.write_all(text.as_bytes())
        .and_then(|()| file.sync_all())
        .map_err(|e| io_error("write", &temporary.0, e))?;
    drop(file);
    if path.read()?.as_deref() != previous {
        return Err(CHANGED.into());
    }
    fs::rename(&temporary.0, &path.target).map_err(|e| io_error("replace", &path.target, e))?;
    if let Ok(directory) = fs::File::open(directory) {
        if let Err(error) = directory.sync_all() {
            eprintln!("[settings] cannot sync display settings directory: {error}");
        }
    }
    if let Some(directory) = path.link.parent() {
        prune_backups(directory, created.as_deref());
    }
    Ok(Written::Replaced)
}

/// Local time as YYYYmmdd-HHMMSS for backup names.
pub fn local_stamp() -> String {
    // SAFETY: time/localtime_r only write the provided out-parameters.
    unsafe {
        let now = libc::time(std::ptr::null_mut());
        let mut tm: libc::tm = std::mem::zeroed();
        if libc::localtime_r(&now, &mut tm).is_null() && libc::gmtime_r(&now, &mut tm).is_null() {
            return "00000000-000000".into();
        }
        format!(
            "{:04}{:02}{:02}-{:02}{:02}{:02}",
            tm.tm_year + 1900,
            tm.tm_mon + 1,
            tm.tm_mday,
            tm.tm_hour,
            tm.tm_min,
            tm.tm_sec
        )
    }
}

