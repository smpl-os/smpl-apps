    fn target(
        name: &str,
        mode: (i32, i32, f64),
        position: (i32, i32),
        scale: f64,
        transform: i32,
    ) -> Target {
        Target {
            name: name.into(),
            mode: Mode {
                width: mode.0,
                height: mode.1,
                refresh: mode.2,
            },
            x: position.0,
            y: position.1,
            scale,
            transform,
        }
    }

    fn plan(outputs: &[Output], targets: &[Target]) -> Vec<Planned> {
        targets
            .iter()
            .map(|t| Planned {
                selector: choose_selector(
                    outputs.iter().find(|o| o.name == t.name).unwrap(),
                    outputs,
                ),
                target: t.clone(),
            })
            .collect()
    }

