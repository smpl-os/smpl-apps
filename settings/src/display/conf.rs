    #[test]
    fn replace_is_atomic_backed_up_pruned_and_skips_identical_content() {
        let fixture = Fixture::new();
        let path = ConfPath::for_home(&fixture.0).unwrap();
        assert_eq!(path.read().unwrap(), None);
        assert_eq!(
            replace(&path, None, "first\n", "20261003-120000").unwrap(),
            Written::Replaced
        );
        assert!(fixture.backups().is_empty(), "nothing to back up");
        fs::set_permissions(&path.target, fs::Permissions::from_mode(0o640)).unwrap();
        fs::write(fixture.hypr().join("monitors.conf.bak-scroll"), "manual").unwrap();
        let mut previous = "first\n".to_string();
        for second in 0..7 {
            let next = format!("content {second}\n");
            let stamp = format!("20261003-1200{second:02}");
            replace(&path, Some(&previous), &next, &stamp).unwrap();
            previous = next;
        }
        assert_eq!(fs::read_to_string(&path.target).unwrap(), "content 6\n");
        assert_eq!(
            fs::metadata(&path.target).unwrap().permissions().mode() & 0o777,
            0o640
        );
        let backups = fixture.backups();
        assert_eq!(backups.len(), 6, "{backups:?}");
        assert!(backups.contains(&"monitors.conf.bak-scroll".to_string()));
        assert_eq!(backups[0], "monitors.conf.bak-20261003-120002");
        assert_eq!(
            fs::read_to_string(fixture.hypr().join("monitors.conf.bak-20261003-120006")).unwrap(),
            "content 5\n"
        );
        // Same-second collisions get numbered names that sort after the plain one.
        replace(&path, Some("content 6\n"), "content 7\n", "20261003-120006").unwrap();
        assert!(fixture
            .backups()
            .contains(&"monitors.conf.bak-20261003-120006-2".to_string()));
        let before = fixture.backups();
        assert_eq!(
            replace(&path, Some("content 7\n"), "content 7\n", "20261003-130000").unwrap(),
            Written::Unchanged
        );
        assert_eq!(fixture.backups(), before);
        assert!(replace(&path, Some("stale\n"), "content 8\n", "20261003-140000").is_err());
        assert_eq!(fs::read_to_string(&path.target).unwrap(), "content 7\n");
        let leftovers = fs::read_dir(fixture.hypr())
            .unwrap()
            .flatten()
            .filter(|e| e.file_name().to_string_lossy().ends_with(".tmp"))
            .count();
        assert_eq!(leftovers, 0);
    }

