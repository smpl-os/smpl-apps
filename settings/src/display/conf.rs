    #[test]
    fn all_line_forms_parse() {
        let full =
            parse_line("monitor = DP-3, 1920x1080@60, 0x0, 1.5, transform, 3, vrr, 1").unwrap();
        assert_eq!(
            full.form,
            Form::Full {
                mode: "1920x1080@60".into(),
                position: "0x0".into(),
                scale: "1.5".into(),
                transform: 3,
                options: vec![("vrr".into(), "1".into())],
            }
        );
        assert_eq!(
            parse_line("monitor = DP-3, disabled").unwrap().form,
            Form::Disable
        );
        assert_eq!(
            parse_line("monitor = DP-3, transform, 6").unwrap().form,
            Form::Transform(Some(6))
        );
        assert_eq!(
            parse_line("monitor = DP-3, transform, 1.0").unwrap().form,
            Form::Transform(None)
        );
        assert_eq!(
            parse_line("monitor = DP-3, addreserved, 0, 32, 0, 0")
                .unwrap()
                .form,
            Form::AddReserved(vec!["0".into(), "32".into(), "0".into(), "0".into()])
        );
        // Options stop at the first empty key; an empty value is just invalid.
        let Form::Full {
            options, transform, ..
        } = parse_line("monitor = DP-3, preferred, auto, 1, icc, , transform, 1, , vrr, 1")
            .unwrap()
            .form
        else {
            panic!("full line expected");
        };
        assert_eq!(options, vec![("icc".into(), "".into())]);
        assert_eq!(transform, 1);
        for invalid in ["1.0", "abc", "8", "-1", ""] {
            let line = format!("monitor = DP-3, preferred, auto, 1, transform, {invalid}");
            assert!(
                matches!(
                    parse_line(&line).unwrap().form,
                    Form::Full { transform: 0, .. }
                ),
                "{invalid}"
            );
        }
    }

    #[test]
    fn rule_semantics_last_defined_wins_and_selectors_move_to_end() {
        let text = "monitor = DP-3, 1920x1080@60, 0x0, 1, transform, 1\n\
                    monitor = desc:Dell Inc., 1280x1024@75, 100x0, 1\n\
                    monitor = DP-3, transform, 2\n";
        let all = rules(text);
        assert_eq!(
            all.iter().map(|r| r.selector.as_str()).collect::<Vec<_>>(),
            ["desc:Dell Inc.", "DP-3"]
        );
        let dp3 = &live_pair()[1];
        let rule = effective(&all, dp3).unwrap();
        assert_eq!(rule.selector, "DP-3");
        assert_eq!(rule.transform, 2);
        assert_eq!(rule.position, Some((0, 0)));
        // A full line replaces the identical selector with a fresh rule.
        let replaced = rules("monitor = DP-3, preferred, auto, 1, transform, 1\nmonitor = DP-3, preferred, auto, 1\n");
        assert_eq!(replaced.len(), 1);
        assert_eq!(replaced[0].transform, 0);
        // Desc prefixes match and the later rule wins.
        let later = rules("monitor = DP-3, preferred, auto, 1, transform, 1\nmonitor = desc:Dell Inc. DELL, preferred, auto, 1\n");
        assert_eq!(effective(&later, dp3).unwrap().transform, 0);
    }

    #[test]
    fn standalone_transform_and_addreserved_semantics() {
        assert!(rules("monitor = DP-3, transform, 1\n").is_empty());
        let modified = rules("monitor = DP-3, preferred, auto, 1\nmonitor = desc:X, disable\nmonitor = DP-3, transform, 1\n");
        assert_eq!(modified.last().unwrap().selector, "DP-3");
        assert_eq!(modified.last().unwrap().transform, 1);
        let reserved = rules("monitor = DP-3, 1920x1080, 0x0, 1, transform, 3\nmonitor = desc:Y, disable\nmonitor = DP-3, addreserved, 0, 32, 0, 0\n");
        assert_eq!(
            reserved[0].selector, "DP-3",
            "addreserved modifies in place"
        );
        assert_eq!(reserved[0].transform, 3);
        let appended = rules("monitor = DP-3, addreserved, 0, 32, 0, 0\n");
        assert_eq!(appended, vec![Rule::fresh("DP-3")]);
        let disabled =
            rules("monitor = DP-3, preferred, auto, 1, transform, 1\nmonitor = DP-3, disable\n");
        assert!(disabled[0].disabled);
        assert_eq!(disabled[0].transform, 0);
        assert!(effective(&rules("monitor = , preferred, auto, 1\n"), &live_pair()[1]).is_none());
    }

